const faOverrides = fa;

export function translate(language: Language, key: string, params?: Record<string, string | number>): string {
  const template = language === 'fa' ? faOverrides[key] ?? key : key;
  if (!params) return template;
  return Object.entries(params).reduce(
    (acc, [name, value]) => acc.replace(new RegExp(`\\{${name}\\}`, 'g'), String(value)),
    template,
  );
}

/** Format a date respecting the active language (Jalali calendar for Persian). */
export function formatLocalizedDate(
  date: Date | number,
  language: Language,
  options: Intl.DateTimeFormatOptions,
): string {
  try {
    return new Intl.DateTimeFormat(language === 'fa' ? 'fa-IR' : 'en-US', options).format(
      typeof date === 'number' ? new Date(date) : date,
    );
  } catch {
    return String(date);
  }
}

export function useT() {
  const language = useSettings((state) => state.language);
  return useCallback(
    (key: string, params?: Record<string, string | number>) => translate(language, key, params),
    [language],
  );
}

export function useLanguage(): Language {
  return useSettings((state) => state.language);
}
